class UserModel {
  final String id, fullName, username, email, niche, country, level;
  final String? bio, profileImage, coverImage;
  final List<String> platforms;
  final int followers,
      following,
      points,
      credits,
      creditsSpent,
      creditsEarned,
      tasksCompleted,
      tasksCreated,
      totalReviews,
      reviewerTrustLevel,
      reputationScore;
  final double reviewAccuracy;
  final bool isReviewer, isVerified;
  final DateTime createdAt;

  UserModel({
    required this.id,
    required this.fullName,
    required this.username,
    required this.email,
    required this.niche,
    required this.country,
    required this.level,
    required this.platforms,
    required this.createdAt,
    this.bio,
    this.profileImage,
    this.coverImage,
    this.followers = 0,
    this.following = 0,
    this.points = 0,
    this.credits = 100,
    this.creditsSpent = 0,
    this.creditsEarned = 0,
    this.tasksCompleted = 0,
    this.tasksCreated = 0,
    this.totalReviews = 0,
    this.reviewerTrustLevel = 1,
    this.reputationScore = 100,
    this.reviewAccuracy = 0,
    this.isReviewer = false,
    this.isVerified = false,
  });

  factory UserModel.fromJson(Map<String, dynamic> j) => UserModel(
        id: j['id'] ?? '',
        fullName: j['full_name'] ?? '',
        username: j['username'] ?? '',
        email: j['email'] ?? '',
        niche: j['niche'] ?? 'Other',
        country: j['country'] ?? 'United States',
        level: j['level'] ?? 'Beginner',
        platforms: List<String>.from(j['platforms'] ?? []),
        followers: j['followers'] ?? 0,
        following: j['following'] ?? 0,
        points: j['points'] ?? 0,
        credits: j['credits'] ?? 100,
        creditsSpent: j['credits_spent'] ?? 0,
        creditsEarned: j['credits_earned'] ?? 0,
        tasksCompleted: j['tasks_completed'] ?? 0,
        tasksCreated: j['tasks_created'] ?? 0,
        totalReviews: j['total_reviews'] ?? 0,
        reviewerTrustLevel: j['reviewer_trust_level'] ?? 1,
        reputationScore: j['reputation_score'] ?? 100,
        reviewAccuracy: (j['review_accuracy'] ?? 0).toDouble(),
        isReviewer: j['is_reviewer'] ?? false,
        isVerified: j['is_verified'] ?? false,
        bio: j['bio'],
        profileImage: j['profile_image'],
        coverImage: j['cover_image'],
        createdAt: DateTime.parse(
            j['created_at'] ?? DateTime.now().toIso8601String()),
      );

  UserModel copyWith({
    String? id,
    fullName,
    username,
    email,
    niche,
    country,
    level,
    bio,
    profileImage,
    coverImage,
    List<String>? platforms,
    int? followers,
    following,
    points,
    credits,
    creditsSpent,
    creditsEarned,
    tasksCompleted,
    tasksCreated,
    totalReviews,
    reviewerTrustLevel,
    int? reputationScore,
    double? reviewAccuracy,
    bool? isReviewer,
    isVerified,
  }) =>
      UserModel(
        id: id ?? this.id,
        fullName: fullName ?? this.fullName,
        username: username ?? this.username,
        email: email ?? this.email,
        niche: niche ?? this.niche,
        country: country ?? this.country,
        level: level ?? this.level,
        platforms: platforms ?? this.platforms,
        followers: followers ?? this.followers,
        following: following ?? this.following,
        points: points ?? this.points,
        credits: credits ?? this.credits,
        creditsSpent: creditsSpent ?? this.creditsSpent,
        creditsEarned: creditsEarned ?? this.creditsEarned,
        tasksCompleted: tasksCompleted ?? this.tasksCompleted,
        tasksCreated: tasksCreated ?? this.tasksCreated,
        totalReviews: totalReviews ?? this.totalReviews,
        reviewerTrustLevel: reviewerTrustLevel ?? this.reviewerTrustLevel,
        reputationScore: reputationScore ?? this.reputationScore,
        reviewAccuracy: reviewAccuracy ?? this.reviewAccuracy,
        isReviewer: isReviewer ?? this.isReviewer,
        isVerified: isVerified ?? this.isVerified,
        bio: bio ?? this.bio,
        profileImage: profileImage ?? this.profileImage,
        coverImage: coverImage ?? this.coverImage,
        createdAt: createdAt,
      );
}
